using System.Windows;
using System.Windows.Controls;
using System.Windows.Input;
using Npgsql;
using PGMS.Desktop;
using PGMS.PostgreSql;

internal static class IdentityColumnCancellationChecks
{
    private static T Find<T>(Window w,string name)where T:FrameworkElement=>(T)w.FindName(name);
    internal static async Task RunAsync(string connection,Action<bool,string> check)
    {
        string suffix=Guid.NewGuid().ToString("N"),schema="identity_cancel_"+suffix,owner="identity_cancel_owner_"+suffix,qs=SqlIdentifier.Quote(schema),qo=SqlIdentifier.Quote(owner),table=ObjectSql.Relation(schema,"items");
        await using var admin=new NpgsqlConnection(connection);await admin.OpenAsync();
        async Task Sql(string sql){await using var c=new NpgsqlCommand(sql,admin);await c.ExecuteNonQueryAsync();}
        string limited=new NpgsqlConnectionStringBuilder(connection){Username=owner,Pooling=false}.ConnectionString;
        try
        {
            await Sql($"CREATE ROLE {qo} LOGIN;CREATE SCHEMA {qs} AUTHORIZATION {qo};SET ROLE {qo};CREATE TABLE {table}(id integer GENERATED BY DEFAULT AS IDENTITY);RESET ROLE");
            var selected=await new TablePropertiesService(limited).InspectAsync(schema,"items");var column=selected.Columns.Single(c=>c.Name=="id");
            foreach(string route in new[]{"button","escape","close"})
            {
                var dialog=new IdentityColumnDialog(limited,selected,column){ShowInTaskbar=false};Task? pending=null;dialog.Show();dialog.Activate();
                try
                {
                    await dialog.InspectAsync();Find<ComboBox>(dialog,"Operation").SelectedIndex=1;
                    await using var tx=await admin.BeginTransactionAsync();
                    await using(var c=new NpgsqlCommand($"LOCK TABLE ONLY {table} IN ACCESS EXCLUSIVE MODE",admin,tx))await c.ExecuteNonQueryAsync();
                    try
                    {
                        pending=dialog.ApplyAsync();await SequenceApplyCancellationChecks.WaitForLock(connection,schema);
                        check(Find<Button>(dialog,"CancelButton").IsVisible && Find<Button>(dialog,"CancelButton").IsEnabled && !Find<Button>(dialog,"ApplyButton").IsEnabled && !Find<Button>(dialog,"ScriptButton").IsEnabled && !Find<FrameworkElement>(dialog,"Fields").IsEnabled,"Blocked identity Apply protects fields and exposes cancellation: "+route);
                        await dialog.ApplyAsync();await dialog.InspectAsync();
                        if(route=="button")Find<Button>(dialog,"CancelButton").RaiseEvent(new RoutedEventArgs(Button.ClickEvent));
                        else if(route=="escape")dialog.RaiseEvent(new KeyEventArgs(Keyboard.PrimaryDevice,PresentationSource.FromVisual(dialog),Environment.TickCount,Key.Escape){RoutedEvent=Keyboard.PreviewKeyDownEvent});
                        else{dialog.Close();check(dialog.IsVisible,"Closing identity waits for owned operation cleanup");}
                        check(!Find<Button>(dialog,"CancelButton").IsEnabled,"Identity cancellation cannot be requested twice: "+route);
                        await pending.WaitAsync(TimeSpan.FromSeconds(8));
                        check(!dialog.WasApplied && dialog.SnapshotIsStale && dialog.IsVisible && !Find<Button>(dialog,"ApplyButton").IsEnabled,"Canceled identity Apply leaves an open dialog requiring inspection: "+route);
                        check(Find<TextBlock>(dialog,"Feedback").Text.Contains("Result not confirmed") && Find<Button>(dialog,"InspectButton").IsKeyboardFocusWithin,"Identity cancellation explains uncertainty and focuses reinspection: "+route);
                    }
                    finally{dialog.CancelCurrentOperation();await tx.RollbackAsync();if(pending is not null)await pending.WaitAsync(TimeSpan.FromSeconds(8));}
                    check((await new IdentityColumnService(limited).InspectAsync(schema,"items","id")).Generation=="d","Canceled blocked identity write leaves generation unchanged: "+route);
                    if(route=="button"){await dialog.InspectAsync();Find<ComboBox>(dialog,"Operation").SelectedIndex=1;await dialog.ApplyAsync();check(dialog.WasApplied,"Explicit retry after identity reinspection can succeed");await Sql($"ALTER TABLE {table} ALTER COLUMN id SET GENERATED BY DEFAULT");}
                }
                finally{dialog.CancelCurrentOperation();if(pending is not null)await pending.WaitAsync(TimeSpan.FromSeconds(8));dialog.Close();}
            }
            using var listener=new System.Net.Sockets.TcpListener(System.Net.IPAddress.Loopback,0);listener.Start();int port=((System.Net.IPEndPoint)listener.LocalEndpoint).Port;
            var stalled=new IdentityColumnDialog(new NpgsqlConnectionStringBuilder(limited){Port=port,Timeout=2,SslMode=SslMode.Disable}.ConnectionString,selected,column){ShowInTaskbar=false};Task? inspection=null;stalled.Show();
            try
            {
                inspection=stalled.InspectAsync();check(Find<Button>(stalled,"CancelButton").IsEnabled,"Identity inspection can be canceled before PostgreSQL handshake");stalled.CancelCurrentOperation();await inspection.WaitAsync(TimeSpan.FromSeconds(6));
                check(stalled.Snapshot is null && stalled.SnapshotIsStale && Find<TextBlock>(stalled,"Feedback").Text.Contains("canceled") && !Find<Button>(stalled,"ApplyButton").IsEnabled,"Canceled identity startup cannot authorize a write");stalled.CancelCurrentOperation();check(!Find<Button>(stalled,"CancelButton").IsVisible,"Idle identity cancellation has no remaining operation");
            }
            finally{stalled.CancelCurrentOperation();if(inspection is not null)await inspection.WaitAsync(TimeSpan.FromSeconds(6));stalled.Close();listener.Stop();}
        }
        finally{await Sql($"DROP SCHEMA IF EXISTS {qs} CASCADE;DROP ROLE IF EXISTS {qo}");}
    }
}
