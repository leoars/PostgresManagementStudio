using System.IO;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Threading;
using Npgsql;
using PGMS.Desktop;
using PGMS.Desktop.ViewModels;
using PGMS.PostgreSql;

// Start/Stop/Restart of a local PostgreSQL service (M1038). Nothing here controls a real service or raises a UAC prompt: the controller is replaced.
internal static class LocalServiceChecks
{
    internal static async Task RunAsync(string connection, Action<bool, string> check)
    {
        var edb = LocalServerServices.ParseImagePath("\"C:\\Program Files\\PostgreSQL\\17\\bin\\pg_ctl.exe\" runservice -N \"postgresql-x64-17\" -D \"D:\\PG Data\\17\" -w", "key");
        check(edb == new LocalPostgresService("postgresql-x64-17", "D:\\PG Data\\17", null), "The service name and quoted data directory are read from an EDB pg_ctl image path");
        check(LocalServerServices.ParseImagePath("C:\\pg\\bin\\pg_ctl.exe runservice -D C:\\pgdata", "pgsql")?.Name == "pgsql" && LocalServerServices.ParseImagePath("C:\\Windows\\system32\\svchost.exe -k netsvcs", "x") is null
            && LocalServerServices.ParseImagePath("C:\\pg\\bin\\pg_ctl.exe start -D C:\\pgdata", "x") is null, "Only pg_ctl runservice entries are services; without -N the registry key name is used");

        string dir = Path.Combine(Path.GetTempPath(), "pgms-svc-" + Guid.NewGuid().ToString("N")[..8]);
        Directory.CreateDirectory(dir);
        try
        {
            File.WriteAllText(Path.Combine(dir, "postgresql.conf"), "#port = 1111\nport = 5433   # (change requires restart)\nmax_connections = 100\n");
            check(LocalServerServices.ReadPort(dir) == 5433, "The port comes from postgresql.conf, ignoring commented lines");
            File.WriteAllText(Path.Combine(dir, "postgresql.auto.conf"), "# Do not edit this file manually!\nport = '5440'\n");
            check(LocalServerServices.ReadPort(dir) == 5440, "ALTER SYSTEM values in postgresql.auto.conf override postgresql.conf");
            File.WriteAllText(Path.Combine(dir, "postgresql.conf"), "shared_buffers = 128MB\n"); File.Delete(Path.Combine(dir, "postgresql.auto.conf"));
            check(LocalServerServices.ReadPort(dir) == 5432 && LocalServerServices.ReadPort(Path.Combine(dir, "missing")) is null, "Without a port setting the default 5432 applies; unreadable configuration gives no port");
        }
        finally { Directory.Delete(dir, true); }

        check(new[] { "localhost", "LOCALHOST", "127.0.0.1", "127.0.0.2", "::1", "[::1]", Environment.MachineName }.All(LocalServerServices.IsLocalHost)
            && !new[] { "db.example.com", "192.168.0.10", "", null }.Any(LocalServerServices.IsLocalHost), "Only loopback addresses and this computer's name are local");
        LocalPostgresService a = new("pg-a", "C:\\a", 5432), b = new("pg-b", "C:\\b", 5433), c = new("pg-c", "C:\\c", 5433);
        check(LocalServerServices.Find("localhost", 5432, [a, b]) == a && LocalServerServices.Find("db.example.com", 5432, [a, b]) is null && LocalServerServices.Find("127.0.0.1", 5433, [a, b, c]) is null
            && LocalServerServices.Find("127.0.0.1", 9999, [a, b]) is null, "A service matches a local connection by port; remote hosts and ambiguous ports match none");

        check(LocalServerServices.ParseState("NOME_DO_SERVIÇO: pg\r\n    TIPO   : 10  WIN32_OWN_PROCESS\r\n    ESTADO   : 4  RUNNING\r\n                (STOPPABLE, PAUSABLE)\r\n    CÓDIGO_DE_SAÍDA_DO_WIN32 : 0  (0x0)") == LocalServiceState.Running
            && LocalServerServices.ParseState("SERVICE_NAME: pg\n        TYPE : 10  WIN32_OWN_PROCESS\n        STATE : 1  STOPPED\n        WIN32_EXIT_CODE : 1077  (0x435)") == LocalServiceState.Stopped
            && LocalServerServices.ParseState("[SC] OpenService FAILED 1060") == LocalServiceState.Unknown, "Service state is parsed from sc.exe output in Portuguese and English Windows");

        var start = LocalServerServices.CreateControlStartInfo("postgresql-x64-17", LocalServiceAction.Restart);
        check(start.Verb == "runas" && start.UseShellExecute && start.FileName.EndsWith("powershell.exe", StringComparison.OrdinalIgnoreCase) && start.Arguments.Contains("Restart-Service -Name 'postgresql-x64-17' -Force", StringComparison.Ordinal),
            "Restart runs Restart-Service elevated through the UAC prompt");
        check(LocalServerServices.CreateControlStartInfo("pg", LocalServiceAction.Start).Arguments.Contains("Start-Service -Name 'pg'\"", StringComparison.Ordinal)
            && LocalServerServices.CreateControlStartInfo("pg", LocalServiceAction.Stop).Arguments.Contains("Stop-Service -Name 'pg' -Force", StringComparison.Ordinal), "Start and Stop use their own cmdlets");
        bool rejected = false;
        try { LocalServerServices.CreateControlStartInfo("pg'; Remove-Item C:\\x; '", LocalServiceAction.Stop); } catch (ArgumentException) { rejected = true; }
        check(rejected && !LocalServerServices.IsValidServiceName("a/b"), "Service names that could escape the PowerShell command are refused");

        // Read-only discovery on this machine: registry and configuration files only, no service is controlled.
        var discovered = LocalServerServices.Discover();
        foreach (var found in discovered) Console.WriteLine($"INFO: local PostgreSQL service {found.Name}, port {found.Port?.ToString() ?? "unknown"}, state {LocalServerServices.QueryState(found.Name)}");
        check(discovered.All(s => s.Name.Length > 0 && s.DataDirectory.Length > 0), $"Discovery of local PostgreSQL services runs without privileges ({discovered.Count} found)");

        // Menu and flow with a fake service and controller.
        var service = new LocalPostgresService("pg-fake", "C:\\fake\\data", new NpgsqlConnectionStringBuilder(connection).Port);
        var state = LocalServiceState.Running;
        var calls = new List<LocalServiceAction>();
        bool confirm = false; string? asked = null;
        var window = new MainWindow
        {
            ShowInTaskbar = false, LocalServiceResolver = (_, _) => (service, state),
            LocalServiceController = (name, action) => { calls.Add(action); state = action == LocalServiceAction.Stop ? LocalServiceState.Stopped : LocalServiceState.Running; return Task.FromResult(state); },
            ConfirmServiceAction = message => { asked = message; return confirm; }
        };
        window.Show();
        try
        {
            await window.ConnectExplorerAsync(connection);
            var tree = (TreeView)window.FindName("ExplorerTree");
            async Task<Dictionary<string, MenuItem>> ServerMenu()
            {
                if (tree.Items.Count == 0) return [];
                ((CatalogNode)tree.Items[0]).IsSelected = true;
                await Dispatcher.Yield(DispatcherPriority.ApplicationIdle);
                var menu = tree.ContextMenu; menu.PlacementTarget = tree; menu.IsOpen = true;
                await Dispatcher.Yield(DispatcherPriority.ApplicationIdle);
                var items = menu.Items.OfType<MenuItem>().ToDictionary(m => m.Name); menu.IsOpen = false; return items;
            }
            var running = await ServerMenu();
            check(!running["ExplorerStartService"].IsEnabled && running["ExplorerStopService"].IsEnabled && running["ExplorerRestartService"].IsEnabled
                && ((string)running["ExplorerStopService"].ToolTip).Contains("pg-fake", StringComparison.Ordinal), "With the service running, Stop and Restart are enabled and Start is not");

            await window.ControlLocalServiceAsync(LocalServiceAction.Stop);
            check(calls.Count == 0 && asked?.Contains("C:\\fake\\data", StringComparison.Ordinal) == true && tree.Items.Count > 0, "Stop asks first, names the data directory, and does nothing when declined");
            confirm = true;
            await window.ControlLocalServiceAsync(LocalServiceAction.Restart);
            for (int i = 0; i < 100 && tree.Items.Count == 0; i++) await Task.Delay(50);
            check(calls.SequenceEqual([LocalServiceAction.Restart]) && tree.Items.Count > 0 && ((TextBlock)window.FindName("Status")).Text.Contains("pg-fake is running", StringComparison.Ordinal), "Restart runs after confirmation and Object Explorer reconnects");
            await window.ControlLocalServiceAsync(LocalServiceAction.Stop);
            check(calls[^1] == LocalServiceAction.Stop && tree.Items.Count == 0, "A confirmed Stop disconnects Object Explorer");

            window.LocalServiceController = (_, _) => Task.FromException<LocalServiceState>(new OperationCanceledException());
            await window.ConnectExplorerAsync(connection);
            state = LocalServiceState.Running;
            await window.ControlLocalServiceAsync(LocalServiceAction.Restart);
            check(((TextBlock)window.FindName("Status")).Text.Contains("cancelled", StringComparison.Ordinal) && tree.Items.Count > 0, "Declining the administrator prompt leaves Object Explorer connected");

            window.LocalServiceResolver = (_, _) => (null, LocalServiceState.Unknown);
            var remote = await ServerMenu();
            check(new[] { "ExplorerStartService", "ExplorerStopService", "ExplorerRestartService" }.All(n => !remote[n].IsEnabled && ToolTipService.GetShowOnDisabled(remote[n])) && remote["ExplorerReloadConfiguration"].IsEnabled,
                "Without a matching local service the items stay visible but disabled with an explanation, as SSMS greys them");
        }
        finally { window.Close(); }
    }
}
