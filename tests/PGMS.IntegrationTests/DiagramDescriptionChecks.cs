using System.Text;
using System.Text.Json;
using Npgsql;
using PGMS.PostgreSql;

/// <summary>Descriptions in database diagrams and Export for AI (PGMS-045, M1062): COMMENT ON of tables, columns and foreign keys read and written by the
/// diagram, the copy saved in the diagram (format 3), the guards of a change that is only descriptions, a user who does not own the table, and the Markdown
/// of the export and of the optional function pgms.diagram_markdown. Runs inside the throwaway database of <see cref="DiagramChecks"/>.</summary>
internal static class DiagramDescriptionChecks
{
    internal static async Task RunAsync(string connection, Action<bool, string> check)
    {
        await using var admin = new NpgsqlConnection(connection);
        await admin.OpenAsync();
        async Task Sql(string sql) { await using var command = new NpgsqlCommand(sql, admin); await command.ExecuteNonQueryAsync(); }
        async Task<object?> Scalar(string sql) { await using var command = new NpgsqlCommand(sql, admin); return await command.ExecuteScalarAsync(); }
        async Task<string?> Refused(Func<Task> action) { try { await action(); return null; } catch (Exception ex) when (ex is ArgumentException or InvalidOperationException or PostgresException) { return ex.Message; } }
        var diagrams = new DiagramService(connection);
        string editorConnection = new NpgsqlConnectionStringBuilder(connection) { Username = "pgms_ds_editor", Password = null }.ConnectionString;

        await Sql("""
            CREATE SCHEMA ds;
            CREATE TABLE ds.customers (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email text NOT NULL CONSTRAINT customers_email_key UNIQUE, name text NOT NULL DEFAULT 'a|b', note text);
            COMMENT ON TABLE ds.customers IS 'People who buy.';
            COMMENT ON COLUMN ds.customers.email IS 'Login e-mail | unique per customer.';
            CREATE TABLE ds.orders (id integer PRIMARY KEY, customer_id integer NOT NULL CONSTRAINT orders_customer_fk REFERENCES ds.customers(id) ON DELETE CASCADE,
                total numeric(12,2) NOT NULL CONSTRAINT orders_total_check CHECK (total >= 0), placed date);
            COMMENT ON CONSTRAINT orders_customer_fk ON ds.orders IS E'Each order belongs\nto one customer.';
            CREATE INDEX orders_total_positive ON ds.orders (total) WHERE total > 0;
            CREATE TABLE ds.lines (order_id integer NOT NULL CONSTRAINT lines_order_fk REFERENCES ds.orders(id), qty integer NOT NULL);
            CREATE INDEX lines_order ON ds.lines (order_id);
            CREATE ROLE pgms_ds_owner NOLOGIN;
            CREATE ROLE pgms_ds_editor LOGIN;
            CREATE TABLE ds.foreign_owned (id integer PRIMARY KEY, label text);
            ALTER TABLE ds.foreign_owned OWNER TO pgms_ds_owner;
            """);
        try
        {
            string[] names = ["customers", "orders", "lines"];
            var placements = names.Select((n, i) => new DiagramTablePlacement("ds", n, 20 + 220 * i, 20)).ToArray();
            var read = await diagrams.ReadTablesAndIndexesAsync(placements, []);
            TableDesign D(string table) => read.Tables.Single(t => t.Name == table);
            var customers = D("customers"); var orders = D("orders");
            check(DiagramDescriptions.Of(customers).Select(d => (d.Object, d.Name, d.Text)).SequenceEqual([("table", (string?)null, "People who buy."), ("column", "email", "Login e-mail | unique per customer.")])
                && DiagramDescriptions.Of(orders).Single() is { Object: "foreignKey", Name: "orders_customer_fk", Text: "Each order belongs\nto one customer." }, "The diagram reads the COMMENT ON of tables, columns and foreign keys from the catalog");
            check(read.NotOwned.Count == 0, "The tables of the superuser test role count as owned");

            // A change that is only descriptions is a DescriptionEdit, not the locked, compared change of the Table Designer.
            var described = customers with
            {
                Comment = "Buyers of the store.",
                Columns = customers.Columns.Select(c => c.Name switch { "email" => c with { Comment = null }, "note" => c with { Comment = "Free text it's ok\\." }, _ => c }).ToArray()
            };
            var orderDescribed = orders with { ForeignKeys = orders.ForeignKeys.Select(k => k with { Comment = "Order → customer." }).ToArray() };
            var changes = DiagramSchemaChanges.Build([(customers, described), (orders, orderDescribed)], []);
            check(changes.Edits.Count == 2 && changes.Edits.All(e => e is DescriptionEdit) && changes.Unapplied.Count == 0, "Description changes alone become description edits");
            check(changes.Script.Sql.Contains("COMMENT ON TABLE \"ds\".\"customers\" IS E'Buyers of the store.';") && changes.Script.Sql.Contains("COMMENT ON COLUMN \"ds\".\"customers\".\"email\" IS NULL;")
                && changes.Script.Sql.Contains("COMMENT ON COLUMN \"ds\".\"customers\".\"note\" IS E'Free text it''s ok\\\\.';") && changes.Script.Sql.Contains("COMMENT ON CONSTRAINT \"orders_customer_fk\" ON \"ds\".\"orders\" IS E'Order → customer.';"),
                "The script is COMMENT ON for the table, the column (NULL removes it) and the constraint, with the text escaped");
            var structural = customers with { Comment = "x", Columns = [.. customers.Columns, new DesignColumn(null, "extra", "integer", true) { Comment = "New column." }] };
            check(DiagramSchemaChanges.Build([(customers, structural)], []).Edits.Single() is TableDesignEdit, "A change with structure and descriptions stays one Table Designer change");

            // The 4 KiB limit counts UTF-8 bytes; descriptions already in the catalog are not checked.
            string limit = new('a', DiagramDescriptions.MaxBytes), over = new string('é', 2049);
            check(DiagramDescriptions.LimitError(limit) is null && DiagramDescriptions.LimitError(over) is { } tooLong && tooLong.Contains("4096") && Encoding.UTF8.GetByteCount(over) == 4098, "A description can have 4096 bytes of UTF-8, not more");
            check(await Refused(() => Task.FromResult(DiagramSchemaChanges.Build([(customers, customers with { Comment = over })], []))) is { } refusedLimit && refusedLimit.Contains("ds.customers"), "A description over the limit is refused before the script is built");
            var longInCatalog = customers with { Comment = over };
            check(await Refused(() => Task.FromResult(DiagramSchemaChanges.Build([(longInCatalog, longInCatalog with { Columns = longInCatalog.Columns.Select(c => c.Name == "note" ? c with { Comment = "n" } : c).ToArray() })], []))) is null,
                "A long description read from the catalog does not block other changes");

            // Saved: the catalog changes and the diagram keeps a copy, format 3.
            var layout = new DiagramLayout { Tables = placements.Select(p => p with { Oid = read.Tables.Single(t => t.Name == p.Name).Oid }).ToArray() };
            var saved = await diagrams.SaveWithLayoutAsync(null, "Model", layout, changes.Edits);
            check((string?)await Scalar("SELECT obj_description('ds.customers'::regclass, 'pg_class')") == "Buyers of the store." && await Scalar("SELECT col_description('ds.customers'::regclass, 2)") is DBNull
                && (string?)await Scalar("SELECT col_description('ds.customers'::regclass, 4)") == "Free text it's ok\\." && (string?)await Scalar("SELECT obj_description(oid, 'pg_constraint') FROM pg_constraint WHERE conname = 'orders_customer_fk'") == "Order → customer.",
                "Save applies the descriptions to the catalog");
            string json = (string)(await Scalar($"SELECT definition::text FROM pgms.diagrams WHERE diagram_id={saved.Info.Id}"))!;
            using (var document = JsonDocument.Parse(json))
            {
                var root = document.RootElement;
                var first = root.GetProperty("tables")[0].GetProperty("descriptions");
                check(root.GetProperty("format").GetInt32() == 3 && root.GetProperty("catalogRead").ValueKind == JsonValueKind.String && first.GetArrayLength() == 2
                    && first[0].GetProperty("object").GetString() == "table" && first[0].GetProperty("text").GetString() == "Buyers of the store." && first[0].GetProperty("applied").GetBoolean()
                    && first[1].GetProperty("object").GetString() == "column" && first[1].GetProperty("name").GetString() == "note",
                    "The saved diagram is format 3 with a copy of the descriptions of each table, in a stable order");
                check(root.GetProperty("tables")[2].GetProperty("descriptions").GetArrayLength() == 0, "A table without descriptions has an empty copy");
            }
            check(saved.Layout.Tables[1].Descriptions!.Single() is { Object: "foreignKey", Name: "orders_customer_fk", Text: "Order → customer.", Applied: true }, "The layout returned by the save is the one written");
            var again = await diagrams.SaveWithLayoutAsync(saved.Info, "Model", saved.Layout, []);
            string json2 = (string)(await Scalar($"SELECT definition::text FROM pgms.diagrams WHERE diagram_id={saved.Info.Id}"))!;
            static string Copies(string definition) { using var d = JsonDocument.Parse(definition); return string.Join("|", d.RootElement.GetProperty("tables").EnumerateArray().Select(t => t.GetProperty("descriptions").GetRawText())); }
            check(Copies(json2) == Copies(json), "Saving again with no change writes the same copy");

            // Guards of a description edit: the description changed in the database meanwhile, or the column is not the one read.
            var fresh = await diagrams.ReadTablesAndIndexesAsync(placements, []);
            var c2 = fresh.Tables.Single(t => t.Name == "customers");
            var edit = DiagramSchemaChanges.Build([(c2, c2 with { Comment = "Mine." })], []).Edits;
            await Sql("COMMENT ON TABLE ds.customers IS 'Someone else.'");
            check(await Refused(() => diagrams.SaveAsync(again.Info, "Model", again.Layout, edit)) is { } raced && raced.Contains("changed in the database")
                && (string?)await Scalar("SELECT obj_description('ds.customers'::regclass, 'pg_class')") == "Someone else.", "A description changed in the database since the diagram read it is not overwritten");
            var c3 = (await diagrams.ReadTablesAndIndexesAsync(placements, [])).Tables.Single(t => t.Name == "customers");
            var columnEdit = DiagramSchemaChanges.Build([(c3, c3 with { Columns = c3.Columns.Select(c => c.Name == "name" ? c with { Comment = "Full name." } : c).ToArray() })], []).Edits;
            await Sql("ALTER TABLE ds.customers RENAME COLUMN name TO full_name");
            check(await Refused(() => diagrams.SaveAsync(again.Info, "Model", again.Layout, columnEdit)) is { } renamed && renamed.Contains("changed since the diagram read it"), "A column renamed since the diagram read it is refused");
            await Sql("ALTER TABLE ds.customers RENAME COLUMN full_name TO name");
            await Sql("DROP TABLE ds.lines; CREATE TABLE ds.lines (order_id integer NOT NULL CONSTRAINT lines_order_fk REFERENCES ds.orders(id), qty integer NOT NULL); CREATE INDEX lines_order ON ds.lines (order_id)");
            var oldLines = read.Tables.Single(t => t.Name == "lines");
            var tableEdit = DiagramSchemaChanges.Build([(oldLines, oldLines with { Comment = "Lines." })], []).Edits;
            check(await Refused(() => diagrams.SaveAsync(again.Info, "Model", again.Layout, tableEdit)) is { } recreated && recreated.Contains("changed since the diagram read it"), "A table dropped and created again with the same name is refused by its OID");

            // A user who does not own a table: its descriptions stay in the diagram, not applied, with the script for the owner.
            await Sql("""
                ALTER TABLE ds.customers OWNER TO pgms_ds_editor;
                GRANT USAGE ON SCHEMA ds, pgms TO pgms_ds_editor;
                GRANT SELECT ON ALL TABLES IN SCHEMA ds TO pgms_ds_editor;
                GRANT SELECT, INSERT, UPDATE ON pgms.diagrams TO pgms_ds_editor;
                """);
            var editor = new DiagramService(editorConnection);
            var mixed = new[] { new DiagramTablePlacement("ds", "customers", 20, 20), new DiagramTablePlacement("ds", "foreign_owned", 260, 20) };
            var asEditor = await editor.ReadTablesAndIndexesAsync(mixed, []);
            var own = asEditor.Tables.Single(t => t.Name == "customers"); var theirs = asEditor.Tables.Single(t => t.Name == "foreign_owned");
            check(asEditor.NotOwned.SetEquals([theirs.Oid]), "A table owned by another role is reported as not owned");
            var proposed = theirs with { Comment = "Labels of things.", Columns = theirs.Columns.Select(c => c.Name == "label" ? c with { Comment = "Shown to people." } : c).ToArray() };
            var split = DiagramSchemaChanges.Build([(own, own with { Comment = "Mine now." }), (theirs, proposed)], [], asEditor.NotOwned);
            check(split.Edits.Single() is DescriptionEdit && split.Unapplied.Single() is { Table: "foreign_owned" } u && u.Items.Count == 2 && u.Items.All(i => !i.Applied)
                && u.Statements.SequenceEqual(["COMMENT ON TABLE \"ds\".\"foreign_owned\" IS E'Labels of things.';", "COMMENT ON COLUMN \"ds\".\"foreign_owned\".\"label\" IS E'Shown to people.';"]),
                "Descriptions of a table the user does not own leave the save, with the statements for the owner");
            check(split.Script.Sql.Contains("-- COMMENT ON TABLE \"ds\".\"foreign_owned\"") && split.Script.Warnings.Single().Contains("You do not own ds.foreign_owned"), "The review shows those statements commented out, with a warning");
            var editorLayout = new DiagramLayout
            {
                Tables = [mixed[0] with { Oid = own.Oid }, mixed[1] with { Oid = theirs.Oid, Descriptions = split.Unapplied.Single().Items }]
            };
            var byEditor = await editor.SaveWithLayoutAsync(null, "Editor", editorLayout, split.Edits);
            check((string?)await Scalar("SELECT obj_description('ds.customers'::regclass, 'pg_class')") == "Mine now." && await Scalar("SELECT obj_description('ds.foreign_owned'::regclass, 'pg_class')") is DBNull,
                "The save applies what the user owns and leaves the other table as it was");
            var kept = byEditor.Layout.Tables[1].Descriptions!;
            check(kept.Count == 2 && kept.All(d => !d.Applied && d.DatabaseText is null) && kept[0] is { Object: "table", Text: "Labels of things." }, "The saved copy keeps the descriptions not applied, with what the database has");
            string editorJson = (string)(await Scalar($"SELECT definition::text FROM pgms.diagrams WHERE diagram_id={byEditor.Info.Id}"))!;
            check(editorJson.Contains("\"applied\": false") || editorJson.Contains("\"applied\":false"), "The JSON marks them as not applied in the database");
            check(await Refused(() => editor.SaveAsync(byEditor.Info, "Editor", byEditor.Layout, DiagramSchemaChanges.Build([(theirs, proposed)], []).Edits)) is { } denied && denied.Contains("42501"),
                "Without the separation, PostgreSQL refuses the COMMENT ON of a table the user does not own");
            await Sql("COMMENT ON TABLE ds.foreign_owned IS 'Labels of things.'");
            var later = await editor.SaveWithLayoutAsync(byEditor.Info, "Editor", byEditor.Layout, []);
            var afterOwner = later.Layout.Tables[1].Descriptions!;
            check(afterOwner.Single(d => d.Object == "table") is { Applied: true, Text: "Labels of things." } && afterOwner.Single(d => d.Object == "column") is { Applied: false, Text: "Shown to people." },
                "Once the owner runs a statement, that description is applied; the other stays not applied");
            check(DiagramDescriptions.Merge([new("table", null, "x")], [new("table", null, "") { Applied = false }]).Single() is { Applied: false, Text: "", DatabaseText: "x" }
                && DiagramDescriptions.Merge([], [new("table", null, "") { Applied = false }]).Count == 0, "Removing a description not applied is kept until the database has none");

            // Export for AI and the optional function: one query, the same text.
            await Sql("COMMENT ON TABLE ds.customers IS 'People who buy.'; COMMENT ON COLUMN ds.customers.email IS 'Login e-mail | unique per customer.'; COMMENT ON COLUMN ds.customers.note IS NULL; COMMENT ON CONSTRAINT orders_customer_fk ON ds.orders IS E'Each order belongs\\nto one customer.'");
            var model = new DiagramLayout { Tables = [new("ds", "orders", 300, 20), new("ds", "customers", 20, 20), new("ds", "lines", 600, 20), new("ds", "gone", 1, 1)] };
            string markdown = await DiagramMarkdown.RenderAsync(connection, "Sales", model);
            string expected = """
                # Database model: Sales

                > Instructions for AI agents: read this document before writing SQL for this database. Use only the tables, columns and relationships listed here, with the names exactly as written; if what you need is not here, ask instead of guessing a name. Descriptions are the COMMENT ON of each object in PostgreSQL and say what it means. Check the indexes before writing queries that filter, join or sort large tables.

                Database `DBNAME`, diagram "Sales". Written by Postgres Management Studio (PGMS) from the PostgreSQL catalog. 3 table(s).

                ## Tables

                | Table | Description |
                | --- | --- |
                | `ds.customers` | People who buy. |
                | `ds.lines` |  |
                | `ds.orders` |  |

                Tables of the diagram that are no longer in the database: `ds.gone`.

                ## `ds.customers`

                People who buy.

                | Column | Type | Null | Default | Description |
                | --- | --- | --- | --- | --- |
                | `id` | integer | NOT NULL | GENERATED BY DEFAULT AS IDENTITY |  |
                | `email` | text | NOT NULL |  | Login e-mail \| unique per customer. |
                | `name` | text | NOT NULL | `'a\|b'::text` |  |
                | `note` | text | NULL |  |  |

                **Keys and checks:**
                - Primary key `customers_pkey`: `PRIMARY KEY (id)`
                - Unique `customers_email_key`: `UNIQUE (email)`

                **Referenced by:**
                - `ds.orders`, foreign key `orders_customer_fk`: `FOREIGN KEY (customer_id) REFERENCES ds.customers(id) ON DELETE CASCADE`

                **Indexes:**
                - `customers_pkey` (primary key): `CREATE UNIQUE INDEX customers_pkey ON ds.customers USING btree (id)`
                - `customers_email_key`: `CREATE UNIQUE INDEX customers_email_key ON ds.customers USING btree (email)`

                ## `ds.lines`

                _No description._

                | Column | Type | Null | Default | Description |
                | --- | --- | --- | --- | --- |
                | `order_id` | integer | NOT NULL |  |  |
                | `qty` | integer | NOT NULL |  |  |

                **Foreign keys:**
                - `lines_order_fk`: `FOREIGN KEY (order_id) REFERENCES ds.orders(id)`

                **Indexes:**
                - `lines_order`: `CREATE INDEX lines_order ON ds.lines USING btree (order_id)`

                ## `ds.orders`

                _No description._

                | Column | Type | Null | Default | Description |
                | --- | --- | --- | --- | --- |
                | `id` | integer | NOT NULL |  |  |
                | `customer_id` | integer | NOT NULL |  |  |
                | `total` | numeric(12,2) | NOT NULL |  |  |
                | `placed` | date | NULL |  |  |

                **Keys and checks:**
                - Primary key `orders_pkey`: `PRIMARY KEY (id)`
                - Check `orders_total_check`: `CHECK (total >= 0::numeric)`

                **Foreign keys:**
                - `orders_customer_fk`: `FOREIGN KEY (customer_id) REFERENCES ds.customers(id) ON DELETE CASCADE` — Each order belongs<br>to one customer.
                  - No index starts with these columns: deleting or updating a row of the referenced table reads this table to check the key.

                **Referenced by:**
                - `ds.lines`, foreign key `lines_order_fk`: `FOREIGN KEY (order_id) REFERENCES ds.orders(id)`

                **Indexes:**
                - `orders_pkey` (primary key): `CREATE UNIQUE INDEX orders_pkey ON ds.orders USING btree (id)`
                - `orders_total_positive`: `CREATE INDEX orders_total_positive ON ds.orders USING btree (total) WHERE (total > (0)::numeric)`

                """.Replace("DBNAME", new NpgsqlConnectionStringBuilder(connection).Database, StringComparison.Ordinal).Replace("\r\n", "\n", StringComparison.Ordinal);
            if (markdown != expected && Environment.GetEnvironmentVariable("PGMS_MARKDOWN_OUT") is { Length: > 0 } outPath) await File.WriteAllTextAsync(outPath, markdown);
            check(markdown == expected, "Export for AI writes the expected Markdown: instruction, tables in order, columns with type, null, default and description, keys, relationships, indexes and a missing table");
            check(markdown == await DiagramMarkdown.RenderAsync(connection, "Sales", model with { Tables = [.. model.Tables.Reverse()] }), "The order of the tables in the diagram does not change the text");
            await using (var other = new NpgsqlConnection(connection))
            {
                await other.OpenAsync();
                await using (var path = new NpgsqlCommand("SET search_path = ds, public", other)) await path.ExecuteNonQueryAsync();
                await using var session = new NpgsqlCommand(DiagramMarkdown.Query("@d", "@n"), other);
                session.Parameters.AddWithValue("d", NpgsqlTypes.NpgsqlDbType.Jsonb, model.ToJson()); session.Parameters.AddWithValue("n", "Sales");
                check((string)(await session.ExecuteScalarAsync())! != markdown, "The query depends on search_path, which is why the export fixes it");
            }

            check(!await DiagramMarkdown.IsFunctionInstalledAsync(connection), "The function is not installed by Install Diagram Support alone");
            int salesId = (int)(await Scalar($"INSERT INTO pgms.diagrams (name, definition) VALUES ('Sales', '{model.ToJson().Replace("'", "''")}'::jsonb) RETURNING diagram_id"))!;
            await DiagramMarkdown.ApplyAsync(connection, create: true);
            check(await DiagramMarkdown.IsFunctionInstalledAsync(connection) && (string?)await Scalar("SELECT pgms.diagram_markdown('Sales')") == markdown, "pgms.diagram_markdown returns the same Markdown as Export for AI");
            check(await Scalar("SELECT pgms.diagram_markdown('No such diagram')") is DBNull, "The function returns NULL for a diagram that does not exist");
            check((string?)await Scalar("SELECT obj_description('pgms.diagram_markdown(text)'::regprocedure, 'pg_proc')") is { } note && note.Contains("optional")
                && (string?)await Scalar("SELECT array_to_string(proconfig, ',') FROM pg_proc WHERE oid = 'pgms.diagram_markdown(text)'::regprocedure") == "search_path=pg_catalog, pg_temp"
                && (bool)(await Scalar("SELECT provolatile = 's' AND NOT prosecdef FROM pg_proc WHERE oid = 'pgms.diagram_markdown(text)'::regprocedure"))!,
                "The function is STABLE, SECURITY INVOKER, with a fixed search_path and a comment");
            await Sql("GRANT EXECUTE ON FUNCTION pgms.diagram_markdown(text) TO pgms_ds_editor");
            await using (var asReader = new NpgsqlConnection(editorConnection))
            {
                await asReader.OpenAsync();
                await using var call = new NpgsqlCommand("SELECT pgms.diagram_markdown('Sales')", asReader);
                check((string?)await call.ExecuteScalarAsync() == markdown, "Another role with SELECT on pgms.diagrams gets the same text");
            }
            await DiagramMarkdown.ApplyAsync(connection, create: true);
            check(await DiagramMarkdown.IsFunctionInstalledAsync(connection), "Installing again replaces the function");
            await DiagramMarkdown.ApplyAsync(connection, create: false);
            check(!await DiagramMarkdown.IsFunctionInstalledAsync(connection), "Remove drops the function");
            await Sql($"DELETE FROM pgms.diagrams WHERE diagram_id IN ({saved.Info.Id}, {byEditor.Info.Id}, {salesId})");

            // A diagram of format 2 opens without descriptions and gets them on the next save.
            int oldId = (int)(await Scalar("""INSERT INTO pgms.diagrams (name, definition) VALUES ('Format2', '{"format":2,"showIndexes":true,"tables":[{"schema":"ds","name":"customers","x":1,"y":2}],"zoom":1}') RETURNING diagram_id"""))!;
            var old = await diagrams.ReadAsync(oldId);
            check(old.Layout.Format == 2 && old.Layout.Tables.Single().Descriptions is null, "A format 2 diagram opens with no saved descriptions");
            await diagrams.SaveAsync(old.Info, "Format2", old.Layout, []);
            var upgraded = await diagrams.ReadAsync(oldId);
            check(upgraded.Layout.Format == 3 && upgraded.Layout.Tables.Single().Descriptions!.Select(d => d.Text).SequenceEqual(["People who buy.", "Login e-mail | unique per customer."]), "The next save writes format 3 with the descriptions");
            await diagrams.DeleteAsync(oldId);
        }
        finally
        {
            NpgsqlConnection.ClearAllPools();
            await Sql("DROP FUNCTION IF EXISTS pgms.diagram_markdown(text); DROP SCHEMA IF EXISTS ds CASCADE; REVOKE ALL ON pgms.diagrams FROM pgms_ds_editor; REVOKE ALL ON SCHEMA pgms FROM pgms_ds_editor; DROP OWNED BY pgms_ds_editor, pgms_ds_owner; DROP ROLE pgms_ds_editor; DROP ROLE pgms_ds_owner");
        }
    }
}
