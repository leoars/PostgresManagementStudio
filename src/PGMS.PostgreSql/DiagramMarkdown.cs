using Npgsql;

namespace PGMS.PostgreSql;

/// <summary>Export for AI (PGMS-045): a diagram as Markdown for a system prompt or a CLAUDE.md/AGENTS.md, with tables, columns, keys, relationships, indexes
/// and descriptions, read from the catalog in a stable order. One SQL query writes it, so the export of the diagram tab and the optional function
/// pgms.diagram_markdown(name) give the same text: the tab runs the query with its layout, the function with the saved diagram. The query runs with
/// search_path = pg_catalog, pg_temp, so every name outside pg_catalog is schema-qualified and the text does not depend on the session.</summary>
public static class DiagramMarkdown
{
    public const string FunctionSignature = "pgms.diagram_markdown(text)";

    /// <summary>The instruction at the top of the document, for the agent that reads it.</summary>
    public const string Instruction = "Instructions for AI agents: read this document before writing SQL for this database. Use only the tables, columns and relationships listed here, with the names exactly as written; if what you need is not here, ask instead of guessing a name. Descriptions are the COMMENT ON of each object in PostgreSQL and say what it means. Check the indexes before writing queries that filter, join or sort large tables.";

    // Markdown table cells and list items: a pipe would end the cell and a line break the row.
    private static string Escape(string expression) => $"replace(replace(replace({expression}, '|', '\\|'), E'\\r\\n', '<br>'), E'\\n', '<br>')";
    private static string Cell(string expression) => $"COALESCE({Escape(expression)}, '')";
    private static string Code(string expression) => $"CASE WHEN {expression} IS NULL THEN '' ELSE '`' || {Cell(expression)} || '`' END";

    /// <summary>The query, with SQL expressions for the diagram definition (jsonb) and its name (text).</summary>
    public static string Query(string definition, string name) => $$"""
        WITH src AS (SELECT ({{definition}})::jsonb AS def, ({{name}})::text AS dname),
        placed AS (
            SELECT t.ord, t.item->>'schema' AS want_schema, t.item->>'name' AS want_name, COALESCE(
                (SELECT c.oid FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
                 WHERE n.nspname = t.item->>'schema' AND c.relname = t.item->>'name' AND c.relkind IN ('r','p')),
                (SELECT c.oid FROM pg_catalog.pg_class c
                 WHERE (t.item->>'oid') ~ '^[1-9][0-9]{0,9}$' AND (t.item->>'oid')::bigint <= 4294967295 AND c.oid = (t.item->>'oid')::bigint::oid AND c.relkind IN ('r','p'))) AS oid
            FROM src, pg_catalog.jsonb_array_elements(CASE WHEN pg_catalog.jsonb_typeof(src.def->'tables') = 'array' THEN src.def->'tables' ELSE '[]'::jsonb END) WITH ORDINALITY t(item, ord)
        ),
        tabs AS (
            SELECT DISTINCT c.oid, n.nspname::text AS sch, c.relname::text AS tab
            FROM placed p JOIN pg_catalog.pg_class c ON c.oid = p.oid JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
        ),
        sections AS (
            SELECT t.sch, t.tab, pg_catalog.concat_ws(E'\n',
                '## `' || t.sch || '.' || t.tab || '`',
                '',
                COALESCE(NULLIF(pg_catalog.btrim(pg_catalog.obj_description(t.oid, 'pg_class')), ''), '_No description._'),
                '',
                '| Column | Type | Null | Default | Description |',
                '| --- | --- | --- | --- | --- |',
                (SELECT pg_catalog.string_agg('| `' || {{Cell("a.attname::text")}} || '` | ' || {{Cell("pg_catalog.format_type(a.atttypid, a.atttypmod)")}} || ' | '
                        || CASE WHEN a.attnotnull THEN 'NOT NULL' ELSE 'NULL' END || ' | '
                        || CASE a.attidentity WHEN 'a' THEN 'GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY'
                           ELSE CASE WHEN a.attgenerated <> '' THEN '`GENERATED ALWAYS AS (' || {{Cell("pg_catalog.pg_get_expr(d.adbin, d.adrelid)")}} || ') STORED`'
                           ELSE {{Code("pg_catalog.pg_get_expr(d.adbin, d.adrelid)")}} END END || ' | '
                        || {{Cell("pg_catalog.col_description(a.attrelid, a.attnum)")}} || ' |', E'\n' ORDER BY a.attnum)
                 FROM pg_catalog.pg_attribute a LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
                 WHERE a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped),
                (SELECT E'\n**Keys and checks:**\n' || pg_catalog.string_agg('- ' || CASE k.contype WHEN 'p' THEN 'Primary key' WHEN 'u' THEN 'Unique' WHEN 'x' THEN 'Exclusion' ELSE 'Check' END
                        || ' `' || {{Cell("k.conname::text")}} || '`: `' || {{Cell("pg_catalog.pg_get_constraintdef(k.oid, true)")}} || '`'
                        || COALESCE(' — ' || {{Escape("NULLIF(pg_catalog.btrim(pg_catalog.obj_description(k.oid, 'pg_constraint')), '')")}}, ''),
                        E'\n' ORDER BY CASE k.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'x' THEN 2 ELSE 3 END, k.conname COLLATE "C")
                 FROM pg_catalog.pg_constraint k WHERE k.conrelid = t.oid AND k.contype IN ('p','u','x','c')),
                (SELECT E'\n**Foreign keys:**\n' || pg_catalog.string_agg('- `' || {{Cell("k.conname::text")}} || '`: `' || {{Cell("pg_catalog.pg_get_constraintdef(k.oid, true)")}} || '`'
                        || COALESCE(' — ' || {{Escape("NULLIF(pg_catalog.btrim(pg_catalog.obj_description(k.oid, 'pg_constraint')), '')")}}, '')
                        || CASE WHEN EXISTS (
                               SELECT 1 FROM pg_catalog.pg_index i JOIN pg_catalog.pg_class ic ON ic.oid = i.indexrelid JOIN pg_catalog.pg_am am ON am.oid = ic.relam
                               WHERE i.indrelid = k.conrelid AND i.indisvalid AND i.indpred IS NULL AND am.amname IN ('btree','hash') AND i.indnkeyatts >= pg_catalog.cardinality(k.conkey)
                                 AND (SELECT pg_catalog.array_agg(x ORDER BY x) FROM pg_catalog.unnest((i.indkey::int2[])[0:pg_catalog.cardinality(k.conkey) - 1]) x)
                                   = (SELECT pg_catalog.array_agg(x ORDER BY x) FROM pg_catalog.unnest(k.conkey) x))
                           THEN '' ELSE E'\n  - No index starts with these columns: deleting or updating a row of the referenced table reads this table to check the key.' END,
                        E'\n' ORDER BY k.conname COLLATE "C")
                 FROM pg_catalog.pg_constraint k WHERE k.conrelid = t.oid AND k.contype = 'f'),
                (SELECT E'\n**Referenced by:**\n' || pg_catalog.string_agg('- `' || rn.nspname || '.' || r.relname || '`, foreign key `' || {{Cell("k.conname::text")}} || '`: `' || {{Cell("pg_catalog.pg_get_constraintdef(k.oid, true)")}} || '`',
                        E'\n' ORDER BY rn.nspname COLLATE "C", r.relname COLLATE "C", k.conname COLLATE "C")
                 FROM pg_catalog.pg_constraint k JOIN pg_catalog.pg_class r ON r.oid = k.conrelid JOIN pg_catalog.pg_namespace rn ON rn.oid = r.relnamespace
                 WHERE k.confrelid = t.oid AND k.contype = 'f'),
                (SELECT E'\n**Indexes:**\n' || pg_catalog.string_agg('- `' || {{Cell("ic.relname::text")}} || '`'
                        || CASE WHEN i.indisprimary THEN ' (primary key)' WHEN NOT i.indisvalid THEN ' (invalid: the planner does not use it)' ELSE '' END
                        || ': `' || {{Cell("pg_catalog.pg_get_indexdef(i.indexrelid)")}} || '`'
                        || COALESCE(' — ' || {{Escape("NULLIF(pg_catalog.btrim(pg_catalog.obj_description(i.indexrelid, 'pg_class')), '')")}}, ''),
                        E'\n' ORDER BY i.indisprimary DESC, i.indisunique DESC, ic.relname COLLATE "C")
                 FROM pg_catalog.pg_index i JOIN pg_catalog.pg_class ic ON ic.oid = i.indexrelid
                 WHERE i.indrelid = t.oid AND i.indislive)
            ) AS body
            FROM tabs t
        )
        SELECT pg_catalog.concat_ws(E'\n',
            '# Database model: ' || s.dname,
            '',
            '> {{Instruction.Replace("'", "''", StringComparison.Ordinal)}}',
            '',
            'Database `' || pg_catalog.current_database() || '`, diagram "' || s.dname || '". Written by Postgres Management Studio (PGMS) from the PostgreSQL catalog. '
                || (SELECT pg_catalog.count(*) FROM tabs) || ' table(s).',
            '',
            '## Tables',
            '',
            '| Table | Description |',
            '| --- | --- |',
            (SELECT pg_catalog.string_agg('| `' || t.sch || '.' || t.tab || '` | ' || {{Cell("NULLIF(pg_catalog.btrim(pg_catalog.obj_description(t.oid, 'pg_class')), '')")}} || ' |', E'\n' ORDER BY t.sch COLLATE "C", t.tab COLLATE "C") FROM tabs t),
            (SELECT E'\nTables of the diagram that are no longer in the database: ' || pg_catalog.string_agg('`' || COALESCE(p.want_schema, '?') || '.' || COALESCE(p.want_name, '?') || '`', ', ' ORDER BY p.ord) || '.'
             FROM placed p WHERE p.oid IS NULL),
            (SELECT pg_catalog.string_agg(E'\n' || x.body, E'\n' ORDER BY x.sch COLLATE "C", x.tab COLLATE "C") FROM sections x)
        ) || E'\n'
        FROM src s WHERE s.def IS NOT NULL
        """;

    /// <summary>The function a connected agent can call; it reads the saved diagram by name and returns NULL when there is none.</summary>
    public static string CreateFunctionSql => $"""
        CREATE OR REPLACE FUNCTION pgms.diagram_markdown(diagram_name text) RETURNS text
        LANGUAGE sql STABLE SECURITY INVOKER
        SET search_path = pg_catalog, pg_temp
        AS $pgms$
        {Query("SELECT d.definition FROM pgms.diagrams d WHERE d.name = diagram_name", "diagram_name")}
        $pgms$;
        COMMENT ON FUNCTION {FunctionSignature} IS 'Postgres Management Studio (PGMS): the saved diagram of this name as Markdown for AI agents (tables, columns, keys, relationships, indexes and descriptions from the catalog). Read only; optional.';
        """;

    public const string DropFunctionSql = "DROP FUNCTION IF EXISTS pgms.diagram_markdown(text);";

    /// <summary>The Markdown of a layout, read now from the catalog with the same query as the function.</summary>
    public static async Task<string> RenderAsync(string connectionString, string diagramName, DiagramLayout layout, CancellationToken token = default)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync(token).ConfigureAwait(false);
        await using var transaction = await connection.BeginTransactionAsync(System.Data.IsolationLevel.RepeatableRead, token).ConfigureAwait(false);
        await using (var setup = new NpgsqlCommand("SET TRANSACTION READ ONLY; SET LOCAL search_path = pg_catalog, pg_temp", connection, transaction)) await setup.ExecuteNonQueryAsync(token).ConfigureAwait(false);
        await using var command = new NpgsqlCommand(Query("@definition", "@name"), connection, transaction) { CommandTimeout = 60 };
        command.Parameters.AddWithValue("definition", NpgsqlTypes.NpgsqlDbType.Jsonb, layout.ToJson());
        command.Parameters.AddWithValue("name", diagramName);
        string text = (string)(await command.ExecuteScalarAsync(token).ConfigureAwait(false))!;
        await transaction.CommitAsync(token).ConfigureAwait(false);
        return text;
    }

    public static async Task<bool> IsFunctionInstalledAsync(string connectionString, CancellationToken token = default)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync(token).ConfigureAwait(false);
        await using var command = new NpgsqlCommand($"SELECT pg_catalog.to_regprocedure('{FunctionSignature}') IS NOT NULL", connection) { CommandTimeout = 15 };
        return (bool)(await command.ExecuteScalarAsync(token).ConfigureAwait(false))!;
    }

    /// <summary>Runs CreateFunctionSql or DropFunctionSql in one transaction. Creating needs CREATE on the schema pgms; removing, the ownership of the function.</summary>
    public static async Task ApplyAsync(string connectionString, bool create, CancellationToken token = default)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync(token).ConfigureAwait(false);
        await using var transaction = await connection.BeginTransactionAsync(token).ConfigureAwait(false);
        await using (var command = new NpgsqlCommand(create ? CreateFunctionSql : DropFunctionSql, connection, transaction) { CommandTimeout = 30 }) await command.ExecuteNonQueryAsync(token).ConfigureAwait(false);
        await transaction.CommitAsync(token).ConfigureAwait(false);
    }
}
