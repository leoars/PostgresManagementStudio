namespace PGMS.PostgreSql;

public enum ColumnType { Integer, Bigint, Numeric, Text, Boolean, Uuid, Date, TimestampWithTimeZone, Smallint }
public enum ColumnIdentity { None, ByDefault, Always }
public sealed record TableColumn(string Name, ColumnType Type, bool Nullable = true)
{
    public ColumnIdentity Identity { get; init; }
    public SelectedColumnType? InspectedType { get; init; }
    public string TypeDisplay => InspectedType?.ToSql() ?? Type.ToString();
    public string ToSql()
    {
        if(!Enum.IsDefined(Identity))throw new ArgumentException("Select a supported identity generation mode.");
        if (InspectedType is not null)
        {
            if (Identity != ColumnIdentity.None) throw new ArgumentException("Use the dedicated integer choice for identity columns.");
            return SqlIdentifier.Quote(Name) + " " + InspectedType.ToSql() + (Nullable ? " NULL" : " NOT NULL");
        }
        if(Identity!=ColumnIdentity.None && (Type is not(ColumnType.Smallint or ColumnType.Integer or ColumnType.Bigint) || Nullable))
            throw new ArgumentException("Identity requires a smallint, integer or bigint column marked NOT NULL.");
        string generation=Identity switch {ColumnIdentity.None=>"",ColumnIdentity.ByDefault=>" GENERATED BY DEFAULT AS IDENTITY",_=>" GENERATED ALWAYS AS IDENTITY"};
        return SqlIdentifier.Quote(Name) + " " + (Type switch
    {
        ColumnType.Smallint => "smallint", ColumnType.Integer => "integer", ColumnType.Bigint => "bigint", ColumnType.Numeric => "numeric", ColumnType.Text => "text",
        ColumnType.Boolean => "boolean", ColumnType.Uuid => "uuid", ColumnType.Date => "date", ColumnType.TimestampWithTimeZone => "timestamp with time zone",
        _ => throw new ArgumentException("Unsupported column type.")
        }) + generation + (Nullable ? " NULL" : " NOT NULL");
    }
}

public static class ObjectSql
{
    public static string UserSchema(string name)
    {
        string quoted = SqlIdentifier.Quote(name);
        if (name.StartsWith("pg_", StringComparison.OrdinalIgnoreCase) || name.Equals("information_schema", StringComparison.OrdinalIgnoreCase)) throw new ArgumentException("Choose a user schema.");
        return quoted;
    }
    public static string Relation(string schema, string name) => UserSchema(schema) + "." + SqlIdentifier.Quote(name);
}

public sealed record CreateTableEdit(string Schema, string Name, IReadOnlyList<TableColumn> Columns) : IAdministrativeEdit
{
    public TablePartitioning? Partitioning { get; init; }
    public async Task ValidateAsync(Npgsql.NpgsqlConnection connection, Npgsql.NpgsqlTransaction transaction, CancellationToken token = default)
    {
        foreach (var type in Columns.Where(c => c.InspectedType is not null).Select(c => c.InspectedType!.Type).Distinct())
            await DataTypeCatalog.Verify(connection, transaction, type, token).ConfigureAwait(false);
    }
    public Task VerifyAppliedAsync(Npgsql.NpgsqlConnection connection, Npgsql.NpgsqlTransaction transaction, CancellationToken token = default)
        => ValidateAsync(connection, transaction, token);
    public string ToSql()
    {
        string table = ObjectSql.Relation(Schema, Name);
        if (Columns.Count is < 1 or > 100) throw new ArgumentException("Add between 1 and 100 columns.");
        if (Columns.Select(c => c.Name).Distinct(StringComparer.Ordinal).Count() != Columns.Count) throw new ArgumentException("Column names must be unique.");
        return $"CREATE TABLE {table} (\n    " + string.Join(",\n    ", Columns.Select(c => c.ToSql())) + "\n)" +
            (Partitioning is null ? "" : " " + Partitioning.ToSql(Columns)) + ";";
    }
}
