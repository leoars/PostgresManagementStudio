"""Generate RFC3454 Unicode 3.2 membership ranges; development only (Python stdlib).

Data source: https://www.rfc-editor.org/rfc/rfc3454 appendices A, B, C, D.
Runtime needs neither Python nor a network connection. Regenerate from repository root.
"""
from pathlib import Path
import stringprep

tables = {
    "Spaces": stringprep.in_table_c12,
    "Nothing": stringprep.in_table_b1,
    "Unassigned": stringprep.in_table_a1,
    "Prohibited": lambda c: any(getattr(stringprep, "in_table_" + t)(c)
        for t in ("c12", "c21", "c22", "c3", "c4", "c5", "c6", "c7", "c8", "c9")),
    "RightToLeft": stringprep.in_table_d1,
    "LeftToRight": stringprep.in_table_d2,
}
lines = ["// Generated by scripts/Generate-SaslPrepTables.py; RFC3454 Unicode 3.2 data.",
         "namespace PGMS.PostgreSql;", "", "internal static class SaslPrepTables", "{"]
for name, contains in tables.items():
    ranges = []
    start = previous = None
    for code in range(0x110000):
        if contains(chr(code)):
            if start is None:
                start = code
            previous = code
        elif start is not None:
            ranges.extend((start, previous))
            start = previous = None
    if start is not None:
        ranges.extend((start, previous))
    lines.append(f"    internal static readonly int[] {name} =")
    lines.append("    [")
    for i in range(0, len(ranges), 8):
        lines.append("        " + ", ".join(f"0x{v:X}" for v in ranges[i:i+8]) + ",")
    lines.extend(("    ];", ""))
lines.append("}")
Path("src/PGMS.PostgreSql/SaslPrepTables.cs").write_text("\n".join(lines) + "\n", encoding="utf-8")
